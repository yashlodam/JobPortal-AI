package com.jobportal.recruiter.interview.enums;

/**
 * Round type / purpose of the interview.
 */
public enum InterviewRound {

    /** Initial screening call to assess basic fit. */
    SCREENING,

    /** Technical coding/problem solving evaluation. */
    TECHNICAL,

    /** System design and architecture discussion. */
    SYSTEM_DESIGN,

    /** HR / Culture fit round. */
    HR,

    /** Final panel interview with leadership. */
    FINAL,

    /** Reference or background check discussion. */
    REFERENCE_CHECK
}
